#pragma once

#include <memory>
#include <string>
#include <vector>

#include "FaceProfileRunner.h"

#include "Scene3dPanel.h" // SceneCameraView
#include "TrackingReplay.h"
#include "TrackingTypes.h"
#include "WebcamBlink.h"

class AppConfig;
class VisionThread;

// Timeline panel: tracking-recording control (record/stop), recording loader,
// deterministic replay transport (scrub/step/play), checksum divergence
// markers, and what-if re-simulation with edited fusion parameters. Owns the
// TrackingReplay instance - replay is a main-thread concern; live tracking
// and OSC keep running while a recording is being inspected.
class TimelinePanel
{
public:
	// Advances playback and rebuilds the shown frame. Runs every UI frame
	// whether or not the panel is drawn, so a Timeline that is hidden or
	// tabbed behind another panel keeps the replay moving.
	void update(float deltaSeconds);
	void draw(bool* pOpen, AppConfig* config, VisionThread* visionThread);

	// The face profile binding the replayed face is evaluated through, the
	// live one, so a profile edit can be judged against a recorded take
	void setFaceBinding(std::shared_ptr<const FaceProfileBinding> binding) { m_faceBinding= std::move(binding); }
	// The live Blink settings, so a settings edit can be judged against a
	// recorded take. A change re-evaluates the shown frame from a pre-roll.
	void setBlinkConfig(const BlinkConfig& config);

	// When active, MainWindow feeds the 3D scene from the replay instead of
	// the live tracking output
	bool isReplayViewActive() const { return m_bReplayViewActive && m_bLoaded && m_replay.didRun(); }
	// Current frame's fused result for the selected view (Recorded / Replayed
	// / What-if), IMU forearm overlay included
	const TrackingFrameResult& getDisplayFused() const { return m_displayFused; }
	// Camera frustums from the RECORDING's config snapshot (not the live one)
	std::vector<SceneCameraView> getSceneCameras() const;
	// The recording's config snapshot itself, for the body lengths a replayed
	// frame was solved with
	const AppConfig& getRecordedConfig() const { return m_replay.getRecordedConfig(); }
	// Current frame's replayed per-camera results (stale cameras carry their
	// last fresh result, like the live preview panes). Pointers are valid for
	// the rest of the current UI frame.
	std::vector<const TrackingFrameResult*> getPerCameraResults() const;
	// The timeline the shown frames come from, for a retarget run over them:
	// an id that changes with the recording, the view and a what-if run (a
	// new id is a new timeline), the current frame's index, any frame's
	// recorded time, and any frame's fused result for the selected view and
	// its per-camera results (null where a camera has none; the pointers
	// live as long as the loaded recording). The face sources are left out:
	// no retarget reads them.
	int getReplayTimelineId() const;
	int getCurrentFrameIndex() const { return m_currentFrame; }
	double getFrameTimeMs(int frameIndex) const;
	void getRetargetInputs(int frameIndex, TrackingFrameResult& outFused,
						   std::vector<const TrackingFrameResult*>& outPerCamera) const;
	// Current frame's recorded stage state while the replay view is active,
	// null when it is not or the frame carries none (a recording made before
	// it was recorded). Valid for the rest of the current UI frame.
	const RecordedTelemetry* getDisplayTelemetry() const;
	// Every frame's recorded stage state in the loaded take, null for a frame
	// without it, gathered once per load. The pointers live as long as the
	// loaded recording. Empty while nothing is loaded.
	const std::vector<const RecordedTelemetry*>& getFrameTelemetry() const { return m_frameTelemetry; }
	// Whether any frame of the loaded take carries its stage state
	bool hasTelemetry() const { return m_bLoaded && m_bHasTelemetry; }
	// Changes with each load, so a reader can tell one take from the next
	int getTakeId() const { return m_takeGeneration; }
	// Current frame's fusion diagnostics for the selected view while the
	// replay view is active, regenerated by the replay (a passthrough frame's
	// are empty), null when it is not active or the frame has none. Valid for
	// the rest of the current UI frame.
	const FusionDiagnostics* getDisplayFusionDiagnostics() const;

private:
	void drawRecordingSection(AppConfig* config, VisionThread* visionThread);
	void drawLoadSection(const AppConfig* config, VisionThread* visionThread);
	void drawTransportSection();
	void drawWhatIfSection();
	void drawFrameInfoSection();
	void refreshRecordingList(const AppConfig* config);
	void setCurrentFrame(int frameIndex);
	// Rebuilds m_displayFused/m_perCameraCopies for the current frame + view
	void rebuildDisplayFrame();
	// The recorded (live) output reconstructed as a displayable result
	void buildRecordedResult(const RecordedFrame& recorded, TrackingFrameResult& outResult) const;
	// The face sources of a recorded frame: the mouth from the record, the
	// phone from the face sidecar's newest sample at or before it, the
	// webcam and the Blink stage from the direct camera's observation. Steps
	// the Blink stage, so frames come in order.
	FaceSources makeReplayFaceSources(int frameIndex);
	// Evaluates the face profile and the Blink stage up to the current
	// frame: frame by frame while the playhead moves forward, from a reset
	// state and a pre-roll after a seek
	void rebuildDisplayFace();

	TrackingReplay m_replay;
	bool m_bLoaded= false;
	std::string m_loadStatus;

	bool m_bReplayViewActive= false;
	int m_currentFrame= 0;
	int m_viewMode= 1; // 0=Recorded, 1=Replayed, 2=What-if
	// Counts the loads and the what-if runs, each a new timeline
	int m_timelineGeneration= 0;
	// Counts the loads alone
	int m_takeGeneration= 0;
	std::vector<const RecordedTelemetry*> m_frameTelemetry;
	bool m_bHasTelemetry= false;

	bool m_bPlaying= false;
	float m_playSpeed= 1.f;
	double m_playheadMs= 0.0; // recorded-time playhead while playing

	std::vector<std::string> m_recordingFiles;
	int m_selectedRecording= -1;

	TrackingReplay::WhatIfParams m_whatIfParams;
	bool m_bWhatIfSeeded= false;
	std::string m_whatIfStatus;

	// Current-frame display data (rebuilt on frame/view change)
	TrackingFrameResult m_displayFused;
	std::vector<TrackingFrameResult> m_perCameraCopies;
	std::vector<bool> m_perCameraCopyValid;
	RecordedTelemetry m_displayTelemetry;
	FusionDiagnostics m_displayDiagnostics;
	bool m_bDisplayDiagnosticsValid= false;
	int m_builtFrame= -1;
	int m_builtViewMode= -1;

	// The replay's own face evaluation, apart from the live one
	std::shared_ptr<const FaceProfileBinding> m_faceBinding;
	FaceProfileRunner m_faceRunner;
	FaceSources m_displayFace;
	int m_faceFrame= -1;
	WebcamBlinkFilter m_blinkFilter;
	BlinkConfig m_blinkConfig;
	// A seek replays this much of the take before the target, so the
	// stateful stages read the target as straight playback would
	static constexpr double k_facePreRollMs= 3000.0;
	// A forward step longer than this many frames counts as a seek
	static constexpr int k_maxFaceCatchUpFrames= 240;
};
